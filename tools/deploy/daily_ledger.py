"""Append one row per daily run to runs/deploy_daily/LEDGER.md (+ LEDGER.json), read from that run's outputs.

    ALMA_DEPLOY_OUT=runs/deploy_daily/<date> .venv/bin/python tools/deploy/daily_ledger.py

For each project: the November-to-date sample size, the frozen candidate's quantile score and rank among all models,
and the best model. Plus the audit result of that run. No verdicts: the CIs need ~60 days / ~20 gas weeks.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.environ["ALMA_DEPLOY_OUT"]
DAILY = os.path.join(ROOT, "runs", "deploy_daily")


def j(p):
    p = os.path.join(OUT, p)
    return json.load(open(p)) if os.path.exists(p) else None


def rank(models, cand, key="qs"):
    sc = {m: v[key] for m, v in models.items() if v.get(key) is not None}
    if cand not in sc:
        return None
    order = sorted(sc, key=sc.get)
    return {"cand": cand, "cand_qs": sc[cand], "rank": order.index(cand) + 1, "of": len(order),
            "best": order[0], "best_qs": sc[order[0]]}


def main():
    row = {"run": os.path.basename(OUT)}
    a = j("AUDIT.json")
    row["audit"] = f"{a['n_checks'] - a['n_fail']}/{a['n_checks']}" if a else "missing"
    o = j("oil/results.json")
    if o:
        w = o["windows"]["nov_2026"]["h1"]
        row["oil"] = dict(n=w.get("n", 0), **(rank(w["models"], "wm_sv") or {})) if w.get("n") else {"n": 0}
    p = j("power/results.json")
    if p:
        w = p["windows"]["nov_2026"]
        row["power"] = dict(n=w["n"], **rank(w["by_candidate"]["wm_power"]["qs"], "wm_power")) if w.get("n") else {"n": 0}
    g = j("gas/results.json")
    if g:
        w = g["windows"]["nov_2026"]
        row["gas"] = (dict(n=w["n_weeks"], **rank(w["kinds"]["thu"]["by_candidate"]["wm_gas_ens"]["qs"], "wm_gas_ens"))
                      if w.get("n_weeks") else {"n": 0})
    c = j("fin/results_corrected.json")
    if c:
        w = c["windows"]["nov_2026"]
        row["crypto"] = dict(n=w["n_days"], **rank(w["by_candidate"]["wm_fin"]["qs"], "wm_fin")) if w.get("n_days") else {"n": 0}
    os.makedirs(DAILY, exist_ok=True)
    lj = os.path.join(DAILY, "LEDGER.json")
    rows = [r for r in (json.load(open(lj)) if os.path.exists(lj) else []) if r["run"] != row["run"]] + [row]
    json.dump(rows, open(lj, "w"), indent=1)

    def cell(x):
        if not x or not x.get("n"):
            return "n = 0"
        unit = {"gas": "wk", "oil": "d", "power": "d", "crypto": "d"}
        return (f"n={x['n']}: **{x['cand']}** QS {x['cand_qs']:.4g}, rank {x['rank']}/{x['of']}"
                + ("" if x["rank"] == 1 else f" (best {x['best']} {x['best_qs']:.4g})"))
    L = ["# Daily deployment ledger (generated by tools/deploy/daily_ledger.py)\n",
         "Frozen models, no retraining; November 2026 to date; quantile score (lower is better), rank among all "
         "models scored. No significance verdict until ~60 days (power, crypto, oil) / ~20 weeks (gas).\n",
         "| run | audit | gas (Thu origin) | power | crypto | oil (1-day) |", "|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['run']} | {r['audit']} | {cell(r.get('gas'))} | {cell(r.get('power'))} | "
                 f"{cell(r.get('crypto'))} | {cell(r.get('oil'))} |")
    L.append("\nSealed ex-ante forecasts and their grades: [EXANTE_LEDGER.md](EXANTE_LEDGER.md)")
    open(os.path.join(DAILY, "LEDGER.md"), "w").write("\n".join(L) + "\n")
    print(L[-2 if len(L) > 5 else -1])


if __name__ == "__main__":
    main()
